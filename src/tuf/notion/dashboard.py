"""Render the analytics ``Dashboard`` into the "TUF Dashboard" Notion page.

Layout contract: everything *below* the marker callout ("Generated by TUF ...") is owned
and regenerated by TUF; everything *above* it belongs to the user (e.g. native Notion chart
views or linked databases). The marker carries a content hash, so the page is only
rewritten when the numbers (or the day) actually change.
"""

from __future__ import annotations

import hashlib
import json
import logging
import re
from datetime import datetime
from decimal import Decimal
from typing import Any

from tuf.analytics.engine import STATUS_EMOJI, Dashboard, gauge
from tuf.categorization.taxonomy import Taxonomy
from tuf.models import LedgerEntry, TxnType
from tuf.money import ZERO, fmt
from tuf.notion.client import NotionClient

log = logging.getLogger(__name__)

MARKER_PREFIX = "Generated by TUF"
_REF = re.compile(r"ref ([0-9a-f]{12})")
LEVEL_EMOJI = {"good": "✅", "info": "💡", "warn": "⚠️", "alert": "🔴"}
SPARK = "▁▂▃▄▅▆▇█"


def rt(
    text: str, *, bold: bool = False, italic: bool = False, color: str = "default"
) -> dict[str, Any]:
    return {
        "type": "text",
        "text": {"content": text[:2000]},
        "annotations": {"bold": bold, "italic": italic, "color": color},
    }


def para(*parts: dict[str, Any], color: str = "default") -> dict[str, Any]:
    return {"type": "paragraph", "paragraph": {"rich_text": list(parts), "color": color}}


def heading(text: str, level: int = 2) -> dict[str, Any]:
    key = f"heading_{level}"
    return {"type": key, key: {"rich_text": [rt(text)]}}


def bullet(*parts: dict[str, Any], children: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    block: dict[str, Any] = {
        "type": "bulleted_list_item",
        "bulleted_list_item": {"rich_text": list(parts)},
    }
    if children:
        block["bulleted_list_item"]["children"] = children
    return block


def toggle(parts: list[dict[str, Any]], children: list[dict[str, Any]]) -> dict[str, Any]:
    return {"type": "toggle", "toggle": {"rich_text": parts, "children": children}}


def callout(
    icon: str, parts: list[dict[str, Any]], color: str = "gray_background"
) -> dict[str, Any]:
    return {
        "type": "callout",
        "callout": {"rich_text": parts, "icon": {"type": "emoji", "emoji": icon}, "color": color},
    }


def kpi(icon: str, label: str, value: str, detail: str = "") -> dict[str, Any]:
    parts = [rt(f"{label}\n", color="gray"), rt(value, bold=True)]
    if detail:
        parts.append(rt(f"\n{detail}", color="gray"))
    return callout(icon, parts)


def columns(*cols: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "type": "column_list",
        "column_list": {"children": [{"type": "column", "column": {"children": c}} for c in cols]},
    }


def image_placeholder(name: str) -> dict[str, Any]:
    return {
        "type": "image",
        "image": {"type": "file_upload", "file_upload": {"id": f"@chart:{name}"}},
    }


def sparkline(values: list[Decimal]) -> str:
    top = max((float(v) for v in values), default=0.0)
    if top <= 0:
        return SPARK[0] * len(values)
    return "".join(SPARK[min(7, int(float(v) / top * 7))] for v in values)


def _entry_line(
    e: LedgerEntry, d: Dashboard, tax: Taxonomy, trip_names: dict[str, str]
) -> dict[str, Any]:
    icon = tax.icon_for(e.primary, e.subcategory)
    if e.counted:
        amount = fmt(e.spending, d.currency)
    elif e.txn_type in (TxnType.PAID_FOR_OTHERS, TxnType.REIMBURSEMENT):
        amount = f"{fmt(e.paid_share, e.currency)} paid for others"
    elif e.txn_type.is_settlement:
        amount = f"settlement {fmt(abs(e.net_contribution), e.currency)}"
    elif e.spending is None:
        amount = f"{fmt(e.my_share, e.currency)} (not converted)"
    else:
        amount = fmt(e.my_share, e.currency)
    parts = [
        rt(f"{icon} {e.title}  "),
        rt(amount, bold=True),
        rt(f"  · {e.date:%b %d}", color="gray"),
    ]
    if e.trip_key and e.trip_key in trip_names:
        parts.append(rt(f"  · 🧳 {trip_names[e.trip_key]}", color="gray"))
    return bullet(*parts)


def build_blocks(
    d: Dashboard, tax: Taxonomy, charts: set[str], trip_names: dict[str, str]
) -> list[dict[str, Any]]:
    cur, m = d.currency, d.month
    month_name = datetime(int(m.month[:4]), int(m.month[5:]), 1).strftime("%B %Y")
    b = m.budget
    blocks: list[dict[str, Any]] = [heading(f"Overview · {month_name}")]

    budget_value = fmt(b.limit, cur) if b.limit else "Not set"
    budget_detail = (
        f"{fmt(b.remaining, cur)} left"
        if b.remaining is not None and b.remaining >= 0
        else f"{fmt(-(b.remaining or ZERO), cur)} over"
        if b.limit
        else "Set MONTHLY_BUDGET"
    )
    days_left = m.days_in_month - m.elapsed_days
    blocks.append(
        columns(
            [
                kpi("💸", "Spent this month", fmt(m.spent, cur), f"{m.expense_count} expenses"),
                kpi(
                    "📅", "Daily average", fmt(m.daily_average, cur), f"over {m.elapsed_days} days"
                ),
            ],
            [
                kpi("🎯", "Monthly budget", budget_value, budget_detail),
                kpi(
                    "📈",
                    "Projected month-end",
                    fmt(m.projected, cur),
                    "estimate at current pace" if m.projection_is_estimate else "final",
                ),
            ],
            [
                kpi(
                    STATUS_EMOJI[b.status],
                    "Budget used",
                    gauge(b.utilization) if b.limit else "—",
                    f"{days_left} days left",
                ),
                kpi(
                    "🤝",
                    "Paid for others",
                    fmt(m.advanced_for_others, cur),
                    f"settled out {fmt(m.settlements_paid, cur)}"
                    f" · in {fmt(m.settlements_received, cur)}",
                ),
            ],
        )
    )
    if "budget-pace" in charts:
        blocks.append(image_placeholder("budget-pace"))

    if d.insights:
        blocks.append(heading("Insights"))
        blocks.extend(bullet(rt(f"{LEVEL_EMOJI.get(i.level, '•')} {i.text}")) for i in d.insights)

    blocks.append(heading("Categories"))
    for name in ("category-donut", "category-budgets"):
        if name in charts:
            blocks.append(image_placeholder(name))
    for c in d.categories:
        if c.amount == 0 and not c.budget:
            continue
        parts = [rt(f"{tax.icon_for(c.name)} {c.name}  "), rt(fmt(c.amount, cur), bold=True)]
        if c.share_pct is not None:
            parts.append(rt(f"  ({c.share_pct}%)", color="gray"))
        if c.budget and c.budget.limit:
            parts.append(
                rt(
                    f"   {STATUS_EMOJI[c.budget.status]} {c.budget.gauge} of "
                    f"{fmt(c.budget.limit, cur)}",
                    color="gray",
                )
            )
        children = [
            bullet(rt(f"{tax.icon_for(c.name, s)} {s}: "), rt(fmt(v, cur), bold=True))
            for s, v in c.subcategories
        ]
        blocks.append(toggle(parts, children) if children else para(*parts))

    blocks.append(heading("Trends"))
    if "monthly" in charts:
        blocks.append(image_placeholder("monthly"))
    weeks = [v for _, v in d.weekly]
    blocks.append(
        para(
            rt("Last 8 weeks  "),
            rt(sparkline(weeks), bold=True),
            rt(
                f"   this week {fmt(weeks[-1], cur)} · last week {fmt(weeks[-2], cur)}",
                color="gray",
            ),
        )
    )
    mom = [x for x in d.mom if x[1] or x[2]][:6]
    if mom:
        items = []
        for cat, now, prev in mom:
            if prev > 0:
                change = ((now - prev) / prev * 100).quantize(Decimal("1"))
                arrow = "▲" if change > 0 else "▼" if change < 0 else "■"
                delta = f"{arrow} {abs(change)}%"
            else:
                delta = "new"
            items.append(
                bullet(
                    rt(f"{tax.icon_for(cat)} {cat}: "),
                    rt(fmt(now, cur), bold=True),
                    rt(f" vs {fmt(prev, cur)} same point last month  {delta}", color="gray"),
                )
            )
        blocks.append(toggle([rt("Month-over-month by category (same days of the month)")], items))

    if d.trips:
        blocks.append(heading("Trips"))
        if "trips" in charts:
            blocks.append(image_placeholder("trips"))
        for t in d.trips[:8]:
            dates = ""
            if t.start:
                dates = f"{t.start:%b %d}" + (f" – {t.end:%b %d, %Y}" if t.end else "")
            parts = [rt(f"🧳 {t.name}  "), rt(fmt(t.total, cur), bold=True)]
            if t.budget:
                parts.append(
                    rt(
                        f"   {STATUS_EMOJI[t.status]} {gauge(t.utilization)} of "
                        f"{fmt(t.budget, cur)}",
                        color="gray",
                    )
                )
            if dates:
                parts.append(rt(f"   {dates}", color="gray"))
            children = [
                bullet(rt(f"{tax.icon_for(c)} {c}: "), rt(fmt(v, cur), bold=True))
                for c, v in t.by_category
            ]
            children += [
                bullet(rt(f"Largest: {title} ({day:%b %d}) "), rt(fmt(v, cur), bold=True))
                for title, day, v in t.largest[:3]
            ]
            blocks.append(toggle(parts, children or [para(rt("No expenses yet."))]))

    if d.recurring:
        blocks.append(heading("Recurring purchases"))
        blocks.extend(
            bullet(
                rt(f"🔁 {r.merchant} ({r.category}): "),
                rt(f"~{fmt(r.monthly_average, cur)}/month", bold=True),
                rt(f" · {r.months} of the last 6 months · last {r.last_date:%b %d}", color="gray"),
            )
            for r in d.recurring[:8]
        )

    if d.recent:
        blocks.append(heading("Recent expenses"))
        blocks.extend(_entry_line(e, d, tax, trip_names) for e in d.recent)

    blocks.append(
        para(
            rt(
                "Spending = your share of each expense (not what you paid for others). "
                "Settlements, deleted expenses and money advanced for others are excluded. "
                "Projections assume the current daily pace continues and are estimates. "
                f"Amounts are in {cur}; foreign-currency expenses count only when converted "
                "with a stored exchange rate.",
                italic=True,
                color="gray",
            )
        )
    )
    return blocks


def content_hash(blocks: list[dict[str, Any]], svgs: dict[str, str]) -> str:
    h = hashlib.sha256(json.dumps(blocks, sort_keys=True, default=str).encode())
    for name in sorted(svgs):
        h.update(name.encode())
        h.update(svgs[name].encode())
    return h.hexdigest()[:12]


def _plain(block: dict[str, Any]) -> str:
    body = block.get(block.get("type", ""), {})
    return "".join(
        t.get("plain_text") or t.get("text", {}).get("content", "")
        for t in body.get("rich_text", [])
    )


def _resolve_images(blocks: list[dict[str, Any]], ids: dict[str, str]) -> list[dict[str, Any]]:
    out = []
    for blk in blocks:
        if blk["type"] == "image":
            name = blk["image"]["file_upload"]["id"].removeprefix("@chart:")
            if name not in ids:
                continue
            blk = {
                "type": "image",
                "image": {"type": "file_upload", "file_upload": {"id": ids[name]}},
            }
        out.append(blk)
    return out


def refresh(
    client: NotionClient,
    page_id: str,
    d: Dashboard,
    tax: Taxonomy,
    svgs: dict[str, str],
    trip_names: dict[str, str],
    now: datetime,
    *,
    force: bool = False,
    dry_run: bool = False,
) -> bool:
    """Regenerate the managed region if its content hash changed. Returns True if updated."""
    blocks = build_blocks(d, tax, set(svgs), trip_names)
    digest = content_hash(blocks, svgs)
    children = client.list_children(page_id)
    marker_idx = next(
        (
            i
            for i, c in enumerate(children)
            if c.get("type") == "callout" and _plain(c).startswith(MARKER_PREFIX)
        ),
        None,
    )
    if marker_idx is not None and not force:
        found = _REF.search(_plain(children[marker_idx]))
        if found and found.group(1) == digest:
            return False
    if dry_run:
        return True

    ids: dict[str, str] = {}
    for name, svg in svgs.items():
        try:
            ids[name] = client.upload_file(f"tuf-{name}.svg", svg.encode("utf-8"), "image/svg+xml")
        except Exception as exc:
            log.warning("chart upload failed for %s (%s); continuing without it", name, exc)
    marker_text = [
        rt(f"{MARKER_PREFIX} · updated {now:%b %d, %Y %H:%M %Z} · ref {digest}", color="gray"),
        rt(
            "\nEverything below this line is regenerated on each sync. Put your own "
            "views and notes above it.",
            italic=True,
            color="gray",
        ),
    ]
    # Never delete databases/pages, even below the marker (e.g. a linked view the user added).
    old = [
        c
        for c in (children[marker_idx + 1 :] if marker_idx is not None else [])
        if c.get("type") not in ("child_database", "child_page", "link_to_page")
    ]
    if marker_idx is None:
        client.append_children(page_id, [callout("⚙️", marker_text)])
    else:
        client.update_block(children[marker_idx]["id"], {"callout": {"rich_text": marker_text}})
    # Append new content first, then delete the old: a failure never leaves an empty page.
    client.append_children(page_id, _resolve_images(blocks, ids))
    for blk in old:
        client.delete_block(blk["id"])
    return True
